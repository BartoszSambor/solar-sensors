"""Generates a Mermaid ER diagram of the database from the SQLAlchemy models.

Usage (from backend/):
    uv run python -m scripts.er_diagram [output]   # default: ../docs/database.mmd

Run by pre-commit on every commit that touches the models.
"""

import re
import sys
from pathlib import Path

from sqlalchemy import Column, Table
from sqlalchemy.dialects import postgresql

from app.auth.models import AuthSession  # noqa: F401  (register models on Base.metadata)
from app.measurements.models import Measurement  # noqa: F401
from app.models import Base
from app.sensors.models import Sensor  # noqa: F401
from app.series.models import Series  # noqa: F401
from app.users.models import User  # noqa: F401

DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "docs" / "database.mmd"


def _column_type(column: Column[object]) -> str:
    # Mermaid attribute types can't contain spaces ("TIMESTAMP WITH TIME ZONE").
    dialect = postgresql.dialect()  # type: ignore[no-untyped-call]
    compiled = column.type.compile(dialect=dialect)
    return re.sub(r"\s+", "_", compiled)


def _column_keys(column: Column[object]) -> str:
    keys = []
    if column.primary_key:
        keys.append("PK")
    if column.foreign_keys:
        keys.append("FK")
    if column.unique or any(
        index.unique and list(index.columns) == [column]
        for index in column.table.indexes
    ):
        keys.append("UK")
    return ", ".join(keys)


def _entity(table: Table) -> list[str]:
    lines = [f"    {table.name} {{"]
    for column in table.columns:
        line = f"        {_column_type(column)} {column.name}"
        if keys := _column_keys(column):
            line += f" {keys}"
        if column.nullable and not column.primary_key:
            line += ' "nullable"'
        lines.append(line)
    lines.append("    }")
    return lines


def _relationships(table: Table) -> list[str]:
    lines = []
    for column in table.columns:
        for fk in column.foreign_keys:
            parent = "|o" if column.nullable else "||"
            label = column.name
            if fk.ondelete:
                label += f", on delete {fk.ondelete.lower()}"
            lines.append(
                f'    {fk.column.table.name} {parent}--o{{ {table.name} : "{label}"'
            )
    return lines


def render() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    lines = [
        "erDiagram",
        "    %% Generated by backend/scripts/er_diagram.py - do not edit by hand.",
    ]
    for table in tables:
        lines += _relationships(table)
    for table in tables:
        lines += _entity(table)
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    output = Path(argv[0]) if argv else DEFAULT_OUTPUT
    content = render()
    if output.exists() and output.read_text() == content:
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content)
    print(f"Updated {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
